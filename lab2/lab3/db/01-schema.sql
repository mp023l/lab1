INSERT INTO auction_mutex VALUES (1);
CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(1000) NOT NULL CHECK (length(trim(name))>0),
 email VARCHAR(254) NOT NULL UNIQUE CHECK (email=lower(email) AND email LIKE '%_@_%._%')
);
CREATE TABLE collectible_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 description VARCHAR(1000) NOT NULL CHECK (length(trim(description))>0),
 owner_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
 item_condition VARCHAR(20) NOT NULL CHECK (item_condition IN ('POOR','FAIR','GOOD','EXCELLENT','MINT'))
);
CREATE TABLE auction_lots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id BIGINT NOT NULL REFERENCES collectible_items(id) ON DELETE RESTRICT,
 start_price NUMERIC(14,2) NOT NULL CHECK (start_price>0),
 bid_step NUMERIC(14,2) NOT NULL CHECK (bid_step>0),
 start_time TIMESTAMP WITH TIME ZONE NOT NULL,
 end_time TIMESTAMP WITH TIME ZONE NOT NULL CHECK (end_time>start_time),
 status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','OPEN','CLOSED','SETTLED','UNSOLD','CANCELLED'))
);
-- Pending deals reserve their items too.
CREATE UNIQUE INDEX one_reserved_lot_per_item ON auction_lots(item_id) WHERE status IN ('OPEN','CLOSED');
CREATE TABLE bids (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lot_id BIGINT NOT NULL REFERENCES auction_lots(id) ON DELETE RESTRICT,
 user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
 amount NUMERIC(14,2) NOT NULL CHECK (amount>0),
 bid_time TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE (id,lot_id,amount)
);
CREATE INDEX bids_by_lot_amount ON bids(lot_id,amount DESC);
CREATE TABLE auction_deals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lot_id BIGINT NOT NULL UNIQUE REFERENCES auction_lots(id) ON DELETE RESTRICT,
 winning_bid_id BIGINT NOT NULL UNIQUE,
 amount NUMERIC(14,2) NOT NULL CHECK (amount>0),
 transfer_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (transfer_status IN ('PENDING','COMPLETED')),
 FOREIGN KEY (winning_bid_id,lot_id,amount) REFERENCES bids(id,lot_id,amount) ON DELETE RESTRICT
);
CREATE INDEX items_by_owner ON collectible_items(owner_id);
CREATE INDEX bids_by_user ON bids(user_id);
