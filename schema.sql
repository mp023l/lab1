SET WRITE_DELAY 0;
CREATE TABLE IF NOT EXISTS accounts (
id BIGINT PRIMARY KEY, username VARCHAR(80) UNIQUE NOT NULL, email VARCHAR(254) UNIQUE NOT NULL,
password_hash VARCHAR(100) NOT NULL, role VARCHAR(10) NOT NULL, state VARCHAR(20) NOT NULL);
CREATE TABLE IF NOT EXISTS auction_state (id INT PRIMARY KEY, payload CLOB NOT NULL);

CREATE TABLE IF NOT EXISTS user_sessions (
 id VARCHAR(36) PRIMARY KEY, account_id BIGINT NOT NULL, device_id VARCHAR(200),
 access_jti VARCHAR(36) NOT NULL, refresh_jti VARCHAR(36) NOT NULL UNIQUE,
 refresh_hash VARCHAR(64) NOT NULL, issued_at TIMESTAMP NOT NULL,
 expires_at TIMESTAMP NOT NULL, status VARCHAR(10) NOT NULL,
 CONSTRAINT fk_session_account FOREIGN KEY(account_id) REFERENCES accounts(id)
);
CREATE INDEX IF NOT EXISTS idx_sessions_account ON user_sessions(account_id);
